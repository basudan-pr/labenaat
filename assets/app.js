function formFields(obj, defs) {
    return defs.map(([key, label, type]) => `<div class="${type==='textarea'?'full':''}"><label for="field_${key}">${esc(label)}</label>${type==='textarea'?`<textarea class="form-field" id="field_${key}" name="${key}" rows="5">${esc(obj[key])}</textarea>`:`<input class="form-field" id="field_${key}" name="${key}" type="${type==='number'?'number':'text'}" ${type==='number'?'min="5" max="95"':''} value="${attr(obj[key])}">`}</div>`).join('')
}

function newItem(tab) {
    return {
        title: '',
        desc: '',
        content: '',
        ...(tab === 'services' ? {
            icon: '✦',
            image: ''
        } : tab === 'projects' ? {
            year: '2026',
            image: ''
        } : {
            date: new Date().toISOString().slice(0, 10),
            author: 'فريق لَبِنات',
            category: tab === 'news' ? 'أخبار الأكاديمية' : 'التلعيب القيمي',
            image: ''
        })
    }
}

function renderCollection() {
    let tab = currentTab,
        arr = db[tab],
        label = COLLECTIONS[tab],
        panel = $('#adminPanel');
    if (editing === -2 || editing >= 0) {
        let idx = editing,
            existing = idx >= 0,
            obj = existing ? arr[idx] : newItem(tab);
        if (!obj) {
            editing = -1;
            renderCollection();
            return
        }
        panel.innerHTML = `<h2>${existing?'تعديل':'إضافة'} ${tab==='news'?'خبر':tab==='posts'?'مقال':tab==='services'?'خدمة':'مشروع'}</h2><p class="admin-intro">${existing?'عدّل الحقول ثم احفظ':'اكتب المعلومات الجديدة ثم احفظها لتظهر في الموقع'}.</p><form id="itemForm"><div class="form-grid">${formFields(obj,FIELDS[tab])}</div><div class="admin-actions"><button class="btn" type="submit">${existing?'حفظ التغييرات':'نشر في النسخة التجريبية'}</button><button class="btn btn-dark" type="button" id="cancelEdit">العودة إلى القائمة</button></div><p class="form-note">لإضافة صورة استخدم مسارها داخل مجلد assets/media أو رابط صورة مسموح. لا توجد صور لنساء بالغات ضمن الملفات التجريبية.</p></form><div id="status"></div>`;
        $('#itemForm').onsubmit = e => {
            e.preventDefault();
            let vals = Object.fromEntries(new FormData(e.currentTarget));
            if (!vals.title.trim()) {
                status('عنوان العنصر مطلوب.', true);
                return
            }
            if (existing) arr[idx] = {
                ...arr[idx],
                ...vals
            };
            else arr.unshift(vals);
            if (save()) {
                editing = -1;
                renderCollection();
                status('تم حفظ ' + (tab === 'posts' ? 'المقال' : tab === 'news' ? 'الخبر' : 'العنصر') + ' بنجاح، ويظهر الآن في الموقع على هذا المتصفح.')
            }
        };
        $('#cancelEdit').onclick = () => {
            editing = -1;
            renderCollection()
        };
        return
    }
    panel.innerHTML = `<h2>إدارة ${label}</h2><p class="admin-intro">أضف عناصر جديدة أو افتح العناصر الحالية لتعديل عناوينها ومحتواها وصورها.</p><div class="admin-actions"><button class="btn" id="addItem">+ إضافة ${tab==='news'?'خبر جديد':tab==='posts'?'مقال جديد':tab==='services'?'خدمة جديدة':'مشروع جديد'}</button><a href="${tab==='posts'?'blog.html':tab+'.html'}" target="_blank" class="btn btn-dark">استعراض الصفحة ↗</a></div><div class="admin-table-wrap"><table class="admin-table"><thead><tr><th>العنوان</th><th>${tab==='news'||tab==='posts'?'تاريخ النشر':'التفاصيل'}</th><th>الإجراء</th></tr></thead><tbody>${arr.map((x,i)=>`<tr><td>${esc(x.title)}</td><td>${esc(x.date||x.year||x.desc?.slice(0,25)||'')}</td><td><button data-edit="${i}">تعديل</button> <button data-delete="${i}">حذف</button></td></tr>`).join('')}</tbody></table></div><div id="status"></div>`;
    $('#addItem').onclick = () => {
        editing = -2;
        renderCollection()
    };
    $$('[data-edit]').forEach(b => b.onclick = () => {
        editing = Number(b.dataset.edit);
        renderCollection()
    });
    $$('[data-delete]').forEach(b => b.onclick = () => {
        let idx = Number(b.dataset.delete);
        if (confirm('هل تريد حذف «' + arr[idx].title + '»؟')) {
            arr.splice(idx, 1);
            save();
            renderCollection();
            status('تم حذف العنصر من بيانات هذا المتصفح.')
        }
    })
}
